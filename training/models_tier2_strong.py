"""
models_tier2_strong.py -- modern, literature-stronger backbones for Tier 2
fracture classification, as an accuracy-push alternative to AlexNet.

Rationale: AlexNet (2012) is a shallow, low-capacity architecture by modern
standards. Published MURA fracture-detection work (e.g. Rajpurkar et al.'s
DenseNet169 baseline, cited in this project's own Paper 3 background
research at ~90.1%) uses much deeper, modern backbones and gets
substantially higher accuracy than anything AlexNet-based is likely to
reach. All backbones below ship directly in tf.keras.applications with
ImageNet weights -- no manual weight conversion needed (unlike the AlexNet
addon, which needed a PyTorch->Keras port since Keras has no official
pretrained AlexNet).

Supported backbones (--backbone flag in train_tier2_strong.py):
    DenseNet169   -- literature-proven specifically on MURA fracture detection.
    DenseNet121   -- smaller/faster DenseNet variant, worth trying as a
                      lower-variance alternative if DenseNet169 overfits on
                      the smaller regions (elbow/hand).
    EfficientNetV2B0 -- modern efficient architecture, strong ImageNet
                      transfer performance, smaller than DenseNet169.
    ConvNeXtTiny  -- 2022 "modernized ConvNet" design (transformer-inspired
                      training recipe applied to a pure CNN), current-
                      generation architecture, strong transfer learning
                      track record.
"""

import tensorflow as tf
from tensorflow.keras import layers, models, regularizers

_BACKBONES = {
    "DenseNet169": (tf.keras.applications.DenseNet169, tf.keras.applications.densenet.preprocess_input),
    "DenseNet121": (tf.keras.applications.DenseNet121, tf.keras.applications.densenet.preprocess_input),
    "EfficientNetV2B0": (tf.keras.applications.EfficientNetV2B0, tf.keras.applications.efficientnet_v2.preprocess_input),
    "ConvNeXtTiny": (tf.keras.applications.ConvNeXtTiny, tf.keras.applications.convnext.preprocess_input),
    "ResNet50": (tf.keras.applications.ResNet50, tf.keras.applications.resnet50.preprocess_input),
}


def build_strong_fracture_classifier(backbone_name: str, img_size: int = 224, num_classes: int = 2,
                                      dropout: float = 0.5, l2_reg: float = 0.0,
                                      freeze_backbone: bool = True,
                                      domain_weights_path: str = None) -> tf.keras.Model:
    """
    Builds <backbone> -> GlobalAveragePooling -> Dropout -> Dense(num_classes,
    softmax, L2-regularized). `freeze_backbone` controls whether the
    backbone's weights train (False) or stay frozen (True) --
    train_tier2_strong.py uses this for its two-phase fine-tuning schedule
    (phase 1: freeze_backbone=True to train only the head; phase 2: rebuild
    with freeze_backbone=False, load phase-1 weights, continue at a lower LR).

    `domain_weights_path`, if given, loads domain-pretrained backbone weights
    (radiology-image-pretrained, not natural-ImageNet-pretrained) into the
    backbone INSTEAD of ImageNet weights. Two sources are supported, and they
    need different loading strategies because of a Keras 3 restriction:

      1. Self-produced GRAZPEDWRI-DX domain-pretraining weights, written by
         pretrain_graz_backbone.py in this same kit, as a NATIVE Keras 3
         `.weights.h5` file (forced by that script's ensure_weights_h5_suffix()
         helper, since Keras 3's save_weights() requires that exact suffix).
         These are generated by instantiating the SAME backbone_cls the SAME
         way as this function does (include_top=False, pooling="avg", same
         img_size), so the two models' layers match exactly -- a plain,
         non-by_name load_weights() is correct here, and Keras 3 does not
         even support by_name=True loading against the native format at all
         (it raises "`by_name` only supports loading legacy '.h5' or
         '.hdf5' files").
      2. RadImageNet's published .h5 files (see README_accuracy_push.md) --
         legacy-format HDF5, which may use different layer names / include
         extra layers, and only exist for ResNet50, DenseNet121, InceptionV3,
         IRV2 -- loaded with by_name=True, skip_mismatch=True, which Keras 3
         still supports for the legacy format specifically.

    No restriction is enforced in code on which backbone name may be paired
    with domain_weights_path, since both sources can legitimately target any
    backbone (GRAZPEDWRI-DX pretraining) or a specific few (RadImageNet) --
    pick the file and backbone_name that actually correspond to one another.
    """
    if backbone_name not in _BACKBONES:
        raise ValueError(f"Unknown backbone {backbone_name!r}; choices: {list(_BACKBONES)}")
    backbone_cls, preprocess_fn = _BACKBONES[backbone_name]

    if domain_weights_path:
        base = backbone_cls(include_top=False, weights=None,
                             input_shape=(img_size, img_size, 3), pooling="avg")
        if domain_weights_path.endswith(".weights.h5"):
            # Keras 3's NATIVE weights format (what pretrain_graz_backbone.py's
            # ensure_weights_h5_suffix() forces save_weights() to produce for
            # self-produced GRAZPEDWRI-DX weights). Keras 3 does not support
            # by_name=True loading against this format at all (raises
            # "`by_name` only supports loading legacy '.h5' or '.hdf5' files").
            # That's fine here: pretrain_graz_backbone.py instantiates this
            # SAME backbone_cls the SAME way (include_top=False, pooling="avg",
            # same img_size) as this function does, so the two models' layers
            # match exactly and a plain, non-by_name load is correct AND
            # stricter (it will error loudly on any real mismatch, rather than
            # silently skipping layers the way skip_mismatch=True would).
            base.load_weights(domain_weights_path)
        else:
            # Legacy HDF5 format (e.g. a RadImageNet release .h5 file), which
            # may use different layer names / include extra layers -- Keras 3
            # still supports by_name + skip_mismatch loading against the
            # legacy format specifically.
            base.load_weights(domain_weights_path, by_name=True, skip_mismatch=True)
        print(f"Loaded domain-pretrained weights from {domain_weights_path}")
    else:
        base = backbone_cls(include_top=False, weights="imagenet",
                             input_shape=(img_size, img_size, 3), pooling="avg")
    base.trainable = not freeze_backbone

    inputs = layers.Input(shape=(img_size, img_size, 3))
    # Inputs arrive in [0,1] (this project's convention); each backbone's own
    # preprocess_input expects its own native range, so rescale to [0,255]
    # first, matching how build_resnet50_region_classifier already does this
    # in models.py (`inputs * 255.0`).
    x = preprocess_fn(inputs * 255.0)
    x = base(x, training=not freeze_backbone)
    x = layers.Dropout(dropout)(x)
    outputs = layers.Dense(
        num_classes, activation="softmax", name="fracture_output",
        kernel_regularizer=regularizers.l2(l2_reg) if l2_reg > 0 else None,
    )(x)
    return models.Model(inputs, outputs, name=f"tier2_{backbone_name}")
